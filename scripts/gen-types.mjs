#!/usr/bin/env node
// Turns components.schemas of the Private Packagist OpenAPI document into src/schema.ts.
//
//   curl -o openapi.json https://packagist.com/openapi.json
//   node scripts/gen-types.mjs openapi.json src/schema.ts

import { readFileSync, writeFileSync } from 'node:fs';

const [input, output = 'src/schema.ts'] = process.argv.slice(2);
if (!input) {
  console.error('usage: node scripts/gen-types.mjs <openapi.json> [src/schema.ts]');
  process.exit(1);
}

const spec = JSON.parse(readFileSync(input, 'utf8'));
const schemas = spec.components?.schemas ?? {};

const renames = { Error: 'ApiErrorBody', '404Error': 'NotFoundErrorBody', TeamPermissions: 'TeamPermissionSet' };
const typeName = (name) => renames[name] ?? name;
const refName = (ref) => typeName(ref.split('/').pop());

function doc(schema, indent) {
  const lines = [];
  if (schema.description) lines.push(...String(schema.description).trim().split('\n'));
  if (schema.example !== undefined && typeof schema.example !== 'object') lines.push(`@example ${JSON.stringify(schema.example)}`);
  if (schema.deprecated) lines.push('@deprecated');
  if (lines.length === 0) return '';
  const safe = lines.map((line) => line.replace(/\*\//g, '*\\/'));
  if (safe.length === 1) return `${indent}/** ${safe[0]} */\n`;
  return `${indent}/**\n${safe.map((line) => `${indent} * ${line}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

function wrap(type) {
  return /[|&]/.test(type) ? `(${type})` : type;
}

function render(schema, indent = '') {
  if (!schema || typeof schema !== 'object') return 'unknown';
  let type;
  if (schema.$ref) {
    type = refName(schema.$ref);
  } else if (schema.allOf) {
    const parts = schema.allOf.map((part) => render(part, indent)).filter((part) => part !== 'unknown');
    type = parts.length === 0 ? 'unknown' : parts.map(wrap).join(' & ');
  } else if (schema.oneOf || schema.anyOf) {
    type = (schema.oneOf ?? schema.anyOf).map((part) => wrap(render(part, indent))).join(' | ');
  } else if (schema.enum) {
    type = schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  } else if (schema.type === 'array') {
    type = `${wrap(render(schema.items, indent))}[]`;
  } else if (schema.type === 'object' || schema.properties) {
    type = renderObject(schema, indent);
  } else if (schema.type === 'integer' || schema.type === 'number') {
    type = 'number';
  } else if (schema.type === 'string') {
    type = 'string';
  } else if (schema.type === 'boolean') {
    type = 'boolean';
  } else {
    type = 'unknown';
  }
  if (schema.nullable && type !== 'unknown') type = `${type} | null`;
  return type;
}

function renderObject(schema, indent) {
  const properties = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  const lines = [];
  for (const [name, property] of Object.entries(properties)) {
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    lines.push(`${doc(property, inner)}${inner}${key}${required.has(name) ? '' : '?'}: ${render(property, inner)};`);
  }
  if (schema.additionalProperties) {
    const value = schema.additionalProperties === true ? 'unknown' : render(schema.additionalProperties, inner);
    lines.push(`${inner}[key: string]: ${value};`);
  }
  if (lines.length === 0) return 'Record<string, unknown>';
  return `{\n${lines.join('\n')}\n${indent}}`;
}

const out = [];
out.push('// Generated by scripts/gen-types.mjs from the Private Packagist OpenAPI document');
out.push(`// (${spec.info?.title ?? 'OpenAPI'} ${spec.info?.version ?? ''}, https://packagist.com/openapi.json). Do not edit by hand.`);
out.push('');
for (const [name, schema] of Object.entries(schemas)) {
  const rendered = render(schema);
  const head = doc(schema, '');
  if (rendered.startsWith('{') && rendered.endsWith('}') && !rendered.includes('} & (') && !schema.nullable) {
    out.push(`${head}export interface ${typeName(name)} ${rendered}`);
  } else {
    out.push(`${head}export type ${typeName(name)} = ${rendered};`);
  }
  out.push('');
}

writeFileSync(output, out.join('\n'));
console.error(`wrote ${output} (${Object.keys(schemas).length} schemas)`);
